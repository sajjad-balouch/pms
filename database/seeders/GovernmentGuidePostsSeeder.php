    private const SITE = 'https://www.assanzameen.com';

    public function run(): void
    {
        $authorId = User::where('role', 'admin')->orderBy('id')->value('id') ?? User::orderBy('id')->value('id');
        if (! $authorId) {
            $this->command?->warn('Koi user nahi mila, posts nahi banin.');

            return;
        }

        $english = GovernmentGuideEnglish::posts();
        $created = 0;
        $updated = 0;

        foreach ($this->posts() as $post) {
            $en = $english[$post['slug']];
            $enHtml = $en['content'] . GovernmentGuideEnglish::footer();
            $urHtml = $this->urduLinks($post['content'] . $this->footerBlock());
            $readTime = max(2, (int) ceil(str_word_count(strip_tags($enHtml)) / 200));

            $existing = Post::where('slug', $post['slug'])->first();

            if (! $existing) {
                Post::create([
                    'user_id' => $authorId,
                    'slug' => $post['slug'],
                    'title' => $en['title'],
                    'title_ur' => $post['title'],
                    'category' => $post['category'],
                    'summary' => $en['summary'],
                    'summary_ur' => $post['summary'],
                    'content' => $enHtml,
                    'content_ur' => $urHtml,
                    'tags' => $post['tags'],
                    'read_time' => $readTime,
                    'status' => 'published',
                ]);
                $created++;

                continue;
            }

            // Admin ki likhi hui English ko nahi chherna; sirf jo abhi Urdu hai usay bharna
            if (! $existing->hasEnglish()) {
                $existing->fill([
                    'title' => $en['title'],
                    'summary' => $en['summary'],
                    'content' => $enHtml,
                    'read_time' => $readTime,
                ]);
                $existing->title_ur = $existing->title_ur ?: $post['title'];
                $existing->summary_ur = $existing->summary_ur ?: $post['summary'];
                $existing->content_ur = $this->urduLinks($existing->content_ur ?: $urHtml);
                $existing->save();
                $updated++;
            }
        }

        $this->command?->info("Nayi posts: {$created}, English add hui: {$updated}");
    }

    /** Urdu article se apni site ke links Urdu version par jayen. */
    private function urduLinks(string $html): string
    {
        return preg_replace('#href="(https://www\.assanzameen\.com/(?:blog|tools)/[^"?]*)"#', 'href="$1?lang=ur"', $html);
    }

